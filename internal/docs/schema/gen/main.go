// Command gen keeps internal/docs/schema in step with the schema's source of
// truth at packages/docs-schema/schema.json: it copies the file next to the Go
// package (so it can be embedded) and writes names_gen.go with a constant for
// every node and mark type, so Go code refers to node types by identifier
// rather than by string literal.
//
// Run via `go generate ./internal/docs/schema/...`.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	pkgDir, err := os.Getwd()
	if err != nil {
		return err
	}
	// go generate runs in the package directory (internal/docs/schema).
	repoRoot := filepath.Clean(filepath.Join(pkgDir, "..", "..", ".."))
	src := filepath.Join(repoRoot, "packages", "docs-schema", "schema.json")
	data, err := os.ReadFile(src)
	if err != nil {
		return fmt.Errorf("read source of truth: %w", err)
	}
	if err := os.WriteFile(filepath.Join(pkgDir, "schema.json"), data, 0o644); err != nil {
		return err
	}

	var def struct {
		Nodes map[string]json.RawMessage `json:"nodes"`
		Marks map[string]json.RawMessage `json:"marks"`
	}
	if err := json.Unmarshal(data, &def); err != nil {
		return err
	}
	nodes := sortedKeys(def.Nodes)
	marks := sortedKeys(def.Marks)

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/docs/schema/gen from packages/docs-schema/schema.json. DO NOT EDIT.\n\n")
	b.WriteString("package schema\n\n")
	b.WriteString("// Node type names declared by the document model.\nconst (\n")
	for _, n := range nodes {
		fmt.Fprintf(&b, "\tNode%s = %q\n", exportName(n), n)
	}
	b.WriteString(")\n\n// Mark type names declared by the document model.\nconst (\n")
	for _, m := range marks {
		fmt.Fprintf(&b, "\tMark%s = %q\n", exportName(m), m)
	}
	b.WriteString(")\n")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("format generated code: %w", err)
	}
	return os.WriteFile(filepath.Join(pkgDir, "names_gen.go"), formatted, 0o644)
}

func exportName(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func sortedKeys(m map[string]json.RawMessage) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
